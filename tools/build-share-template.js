/* =========================================================
   Build share-template.js
   - Bundles the page shell, CSS, icons and engine into one JS file
     so the in-page customizer can generate a standalone share page
     even when index.html is opened from file:// (fetch is blocked there).
   - Default assets are embedded as data URLs so a share page never
     depends on the assets/ folder.
   Usage: node tools/build-share-template.js
   ========================================================= */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');

const MIME = {
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png',
  '.gif': 'image/gif', '.webp': 'image/webp', '.svg': 'image/svg+xml',
  '.mp3': 'audio/mpeg', '.m4a': 'audio/mp4', '.wav': 'audio/wav',
  '.ogg': 'audio/ogg', '.oga': 'audio/ogg'
};

/* ---------------- shell ---------------- */
let shell = read('index.html');

shell = shell.replace(/[ \t]*<link rel="stylesheet" href="styles\.css[^"]*">\s*/,
  '\n  <!--WB_STYLE-->\n');
shell = shell.replace(/[ \t]*<link rel="stylesheet" href="editor\.css[^"]*">\s*/, '\n');
shell = shell.replace(/[ \t]*<script src="data\.js[^"]*"><\/script>\s*/,
  '\n<!--WB_DATA-->\n');
shell = shell.replace(/[ \t]*<script src="cloud-config\.js[^"]*"><\/script>\s*/, '\n');
shell = shell.replace(/[ \t]*<script src="cloud\.js[^"]*"><\/script>\s*/, '\n');
shell = shell.replace(/[ \t]*<script src="icons\.js[^"]*"><\/script>\s*/,
  '\n<!--WB_ICONS-->\n');
shell = shell.replace(/[ \t]*<!-- custom\.js[\s\S]*?-->\s*/, '\n');
shell = shell.replace(/[ \t]*<script src="custom\.js[^"]*"><\/script>\s*/, '\n');
shell = shell.replace(/[ \t]*<script src="editor\.js[^"]*"><\/script>\s*/,
  '\n<!--WB_APP-->\n');
shell = shell.replace(/[ \t]*<script src="share-template\.js[^"]*"><\/script>\s*/, '\n');

const missing = ['<!--WB_STYLE-->', '<!--WB_DATA-->', '<!--WB_ICONS-->', '<!--WB_APP-->']
  .filter((m) => shell.indexOf(m) < 0);
if (missing.length) {
  console.error('index.html is missing expected markup:', missing.join(', '));
  process.exit(1);
}

/* ---------------- default assets ---------------- */
const assets = {};
const assetDir = path.join(root, 'assets');
if (fs.existsSync(assetDir)) {
  fs.readdirSync(assetDir).forEach((name) => {
    const file = path.join(assetDir, name);
    if (!fs.statSync(file).isFile()) return;
    const mime = MIME[path.extname(name).toLowerCase()];
    if (!mime) return;
    assets['assets/' + name] = 'data:' + mime + ';base64,'
      + fs.readFileSync(file).toString('base64');
  });
}

const bundle = {
  css: read('styles.css'),
  icons: read('icons.js'),
  app: read('app.js'),
  shell: shell,
  assets: assets
};

const out = '/* Generated by tools/build-share-template.js — do not edit by hand. */\n'
  + 'window.WB_SHARE_TEMPLATE = ' + JSON.stringify(bundle) + ';\n';

fs.writeFileSync(path.join(root, 'share-template.js'), out, 'utf8');

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log('share-template.js written: ' + kb(Buffer.byteLength(out)));
console.log('  shell ' + kb(Buffer.byteLength(bundle.shell))
  + ' · css ' + kb(Buffer.byteLength(bundle.css))
  + ' · icons ' + kb(Buffer.byteLength(bundle.icons))
  + ' · app ' + kb(Buffer.byteLength(bundle.app))
  + ' · assets ' + Object.keys(assets).length + ' files');
